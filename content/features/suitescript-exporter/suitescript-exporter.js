/**
 * suitescript-exporter.js
 * NetSuite TactaSuite - SuiteScript Exporter
 *
 * @author Blane Maher
 *
 * Generates SuiteScript 2.x TypeScript scaffolds from NetSuite search,
 * dataset, and workbook pages using visible page metadata.
 */
(function () {
  'use strict';

  if (window.__tactaSuiteScriptExporterLoaded) return;
  window.__tactaSuiteScriptExporterLoaded = true;

  var ROOT_ID = 'tacta-suitescript-exporter';

  function getPageKind() {
    var info = window.__tactaPageInfo || {};
    if (info.type === 'dataset' || /\/dataset\//i.test(location.href)) return 'dataset';
    if (info.type === 'workbook' || /\/workbook\//i.test(location.href)) return 'workbook';
    return 'savedsearch';
  }

  function text(selector) {
    var el = document.querySelector(selector);
    return el ? (el.textContent || el.value || '').trim() : '';
  }

  function value(selectors) {
    for (var i = 0; i < selectors.length; i++) {
      var el = document.querySelector(selectors[i]);
      if (el && el.value) return el.value;
    }
    return '';
  }

  function getSearchDefinition() {
    var title = value(['input[name="title"]', 'input[name="searchtitle"]', '#title']) ||
      text('.uir-page-title-firstline') || document.title || 'Exported Search';
    var searchType = value(['#searchtype', 'input[name="searchtype"]', 'select[name="searchtype"]']) || 'transaction';
    var scriptId = value(['input[name="scriptid"]', 'input[name="id"]']) || '';

    return {
      title: title,
      scriptId: scriptId,
      searchType: normalizeSearchType(searchType),
      filters: collectMachineRows(['filter', 'criteria', 'filters', 'rffilter']),
      columns: collectMachineRows(['column', 'result', 'results', 'field'])
    };
  }

  function normalizeSearchType(type) {
    return String(type || 'transaction').replace(/^custom_/, '').toLowerCase();
  }

  function collectMachineRows(keywords) {
    var rows = [];
    var rowNodes = document.querySelectorAll('tr[id*="row"], tr.uir-machine-row-odd, tr.uir-machine-row-even');
    for (var i = 0; i < rowNodes.length; i++) {
      var row = rowNodes[i];
      var id = (row.id || '').toLowerCase();
      var label = (row.textContent || '').replace(/\s+/g, ' ').trim();
      if (!label) continue;
      var likely = keywords.some(function (word) { return id.indexOf(word) >= 0 || label.toLowerCase().indexOf(word) >= 0; });
      if (!likely && rows.length > 40) continue;
      var fields = [];
      row.querySelectorAll('input, select, textarea').forEach(function (el) {
        var raw = el.value || '';
        if (!raw || raw === '- None -') return;
        fields.push({
          name: el.name || el.id || '',
          value: raw,
          text: el.options && el.selectedIndex >= 0 ? el.options[el.selectedIndex].text : raw
        });
      });
      if (fields.length) rows.push({ label: label, fields: fields });
    }
    return rows.slice(0, 80);
  }

  function quote(value) {
    return "'" + String(value == null ? '' : value).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
  }

  function buildSearchTs(def) {
    var columns = inferColumns(def);
    var filters = inferFilters(def);
    return [
      "/**",
      " * Generated by NetSuite TactaSuite from the visible NetSuite saved search page.",
      " * Review filters and joins before committing; NetSuite does not expose every search setting in the DOM.",
      " */",
      "import search = require('N/search');",
      "",
      "export function createSearch(): search.Search {",
      "  return search.create({",
      "    type: " + quote(def.searchType) + ",",
      "    title: " + quote(def.title) + ",",
      def.scriptId ? "    id: " + quote(def.scriptId) + "," : null,
      "    filters: [",
      filters.length ? filters.map(function (f) { return "      " + f; }).join(",\n") : "      // TODO: verify criteria from the source search",
      "    ],",
      "    columns: [",
      columns.length ? columns.map(function (c) { return "      " + c; }).join(",\n") : "      // TODO: add search.createColumn({ name: 'internalid' })",
      "    ]",
      "  });",
      "}",
      "",
      "export function runSearch(limit = 1000): search.Result[] {",
      "  return createSearch().run().getRange({ start: 0, end: limit }) || [];",
      "}"
    ].filter(Boolean).join('\n');
  }

  function inferColumns(def) {
    var columns = [];
    def.columns.forEach(function (row) {
      var field = firstFieldLike(row, ['field', 'column', 'name']);
      if (!field) return;
      var name = cleanId(field.value);
      if (!name || columns.indexOf(name) >= 0) return;
      columns.push(name);
    });
    return columns.slice(0, 50).map(function (name) {
      return "search.createColumn({ name: " + quote(name) + " })";
    });
  }

  function inferFilters(def) {
    var filters = [];
    def.filters.forEach(function (row) {
      var field = firstFieldLike(row, ['field', 'filter']);
      var operator = firstFieldLike(row, ['operator']);
      var valueField = firstFieldLike(row, ['value', 'text']);
      if (!field) return;
      var filter = "[" + quote(cleanId(field.value)) + ", " + quote(cleanOperator(operator && operator.value)) + ", " + quote(valueField ? valueField.value : '') + "]";
      if (filters.indexOf(filter) < 0) filters.push(filter);
    });
    return filters.slice(0, 50);
  }

  function firstFieldLike(row, keys) {
    for (var i = 0; i < row.fields.length; i++) {
      var hay = ((row.fields[i].name || '') + ' ' + (row.fields[i].text || '')).toLowerCase();
      for (var k = 0; k < keys.length; k++) {
        if (hay.indexOf(keys[k]) >= 0) return row.fields[i];
      }
    }
    return row.fields[0] || null;
  }

  function cleanId(value) {
    return String(value || '').replace(/^.*:/, '').replace(/\s+/g, '').replace(/^[^a-z0-9_]+|[^a-z0-9_]+$/gi, '').toLowerCase();
  }

  function cleanOperator(value) {
    var op = String(value || 'anyof').toLowerCase().replace(/\s+/g, '');
    return op || 'anyof';
  }

  function buildAnalyticsTs(kind) {
    var title = text('.uir-page-title-firstline') || document.title || ('Exported ' + kind);
    return [
      "/**",
      " * Generated " + kind + " scaffold from the current NetSuite page.",
      " * NetSuite Analytics pages expose limited definition data in the browser; paste the generated SuiteQL into N/query.",
      " */",
      "import query = require('N/query');",
      "",
      "export interface QueryRow {",
      "  [column: string]: string | number | boolean | null;",
      "}",
      "",
      "export const sourceName = " + quote(title) + ";",
      "",
      "export const suiteql = `",
      "-- TODO: paste or refine the SuiteQL behind this " + kind + ".",
      "SELECT *",
      "FROM transaction",
      "WHERE ROWNUM <= 100",
      "`;",
      "",
      "export function run(): QueryRow[] {",
      "  return query.runSuiteQL({ query: suiteql }).asMappedResults() as QueryRow[];",
      "}"
    ].join('\n');
  }

  function buildCode() {
    var kind = getPageKind();
    if (kind === 'savedsearch') return buildSearchTs(getSearchDefinition());
    return buildAnalyticsTs(kind);
  }

  function copy(textValue) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(textValue);
    }
    var ta = document.createElement('textarea');
    ta.value = textValue;
    ta.style.cssText = 'position:fixed;left:-9999px;top:-9999px;';
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
    return Promise.resolve();
  }

  function download(content) {
    var blob = new Blob([content], { type: 'text/typescript;charset=utf-8;' });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = 'netsuite-export-' + Date.now() + '.ts';
    document.body.appendChild(a);
    a.click();
    setTimeout(function () {
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    }, 100);
  }

  function showPanel() {
    var existing = document.getElementById(ROOT_ID);
    if (existing) {
      existing.remove();
      return;
    }
    var code = buildCode();
    var root = document.createElement('div');
    root.id = ROOT_ID;
    root.className = 'tacta-ssex tacta-toolkit';
    root.innerHTML = [
      '<div class="tacta-ssex-head"><strong>SuiteScript Export</strong><button type="button" data-close>&times;</button></div>',
      '<div class="tacta-ssex-actions"><button type="button" data-copy>Copy TS</button><button type="button" data-download>Download .ts</button></div>',
      '<textarea spellcheck="false"></textarea>'
    ].join('');
    root.querySelector('textarea').value = code;
    root.querySelector('[data-close]').addEventListener('click', function () { root.remove(); });
    root.querySelector('[data-copy]').addEventListener('click', function () { copy(root.querySelector('textarea').value); });
    root.querySelector('[data-download]').addEventListener('click', function () { download(root.querySelector('textarea').value); });
    document.body.appendChild(root);
  }

  function addButton() {
    if (document.getElementById('tacta-ssex-button')) return;
    var btn = document.createElement('button');
    btn.id = 'tacta-ssex-button';
    btn.className = 'tacta-ssex-button tacta-toolkit';
    btn.type = 'button';
    btn.textContent = 'Export TS';
    btn.title = 'Export this NetSuite definition to a SuiteScript 2.x TypeScript scaffold';
    btn.addEventListener('click', function (e) {
      e.preventDefault();
      showPanel();
    });
    var target = document.querySelector('.uir-page-title-secondline') || document.querySelector('.uir-page-title') || document.body.firstChild;
    if (target && target.parentNode) target.parentNode.insertBefore(btn, target.nextSibling);
    else document.body.appendChild(btn);
  }

  function init() {
    setTimeout(addButton, 500);
  }

  window.addEventListener('tacta:featureActivated', function (e) {
    if (e.detail && e.detail.featureId === 'suitescript-exporter') init();
  });
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init, { once: true });
  else init();
})();
